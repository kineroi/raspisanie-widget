'use strict';
// Мост между окнами и программой: окна могут вызывать только эти команды.
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getData: () => ipcRenderer.invoke('get-data'),
  installUpdate: () => ipcRenderer.invoke('install-update'),
  checkUpdate: () => ipcRenderer.invoke('check-update'),
  sync: () => ipcRenderer.invoke('sync'),
  login: () => ipcRenderer.invoke('login'),
  logout: () => ipcRenderer.invoke('logout'),
  setAiKey: (key, base) => ipcRenderer.invoke('set-ai-key', key, base),
  setAiModel: (model) => ipcRenderer.invoke('set-ai-model', model),
  refreshAiModels: () => ipcRenderer.invoke('refresh-ai-models'),
  setAutostart: (on) => ipcRenderer.invoke('set-autostart', on),
  setMiniOnTop: (on) => ipcRenderer.invoke('set-mini-on-top', on),
  setReminders: (on) => ipcRenderer.invoke('set-reminders', on),
  testReminder: () => ipcRenderer.invoke('test-reminder'),
  openMain: () => ipcRenderer.invoke('open-main'),
  openHomework: (date, start) => ipcRenderer.invoke('open-homework', date, start),
  hideMini: () => ipcRenderer.invoke('hide-mini'),
  showMini: () => ipcRenderer.invoke('show-mini'),
  resizeMini: (h) => ipcRenderer.invoke('resize-mini', h),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  expand: (note, classes, theme) => ipcRenderer.invoke('expand', note, classes, theme),
  sendHomework: (req) => ipcRenderer.invoke('send-homework', req),
  homeworkHistory: () => ipcRenderer.invoke('hw-history'),
  deleteFile: (date, fileId) => ipcRenderer.invoke('delete-file', date, fileId),
  onData: (cb) => ipcRenderer.on('data-changed', (_e, data) => cb(data)),
  openGrades: () => ipcRenderer.invoke('open-grades'),
  openAnalysis: () => ipcRenderer.invoke('open-analysis'),
  anLoad: (quarter) => ipcRenderer.invoke('an-load', quarter),
  anSettings: () => ipcRenderer.invoke('an-settings'),
  anSaveSettings: (s) => ipcRenderer.invoke('an-save-settings', s),
  anTexts: (cls, quarter) => ipcRenderer.invoke('an-texts', cls, quarter),
  anSetTexts: (cls, quarter, texts) => ipcRenderer.invoke('an-set-texts', cls, quarter, texts),
  anPickFiles: () => ipcRenderer.invoke('an-pick-files'),
  anPrepare: (cls, quarter, label, paths) => ipcRenderer.invoke('an-prepare', cls, quarter, label, paths),
  anSave: (cls, quarter, texts) => ipcRenderer.invoke('an-save', cls, quarter, texts),
  anOpen: (file, folder) => ipcRenderer.invoke('an-open', file, folder),
  gradesData: () => ipcRenderer.invoke('grades-data'),
  gradesRefresh: () => ipcRenderer.invoke('grades-refresh'),
  setGradeAlerts: (on) => ipcRenderer.invoke('set-grade-alerts', on),
  onGrades: (cb) => ipcRenderer.on('grades-changed', () => cb()),
  openAttestation: () => ipcRenderer.invoke('open-attestation'),
  openAttendance: () => ipcRenderer.invoke('open-attendance'),
  ajLoad: () => ipcRenderer.invoke('aj-load'),
  ajSyncNow: () => ipcRenderer.invoke('aj-sync-now'),
  onAjSynced: (cb) => ipcRenderer.on('aj-synced', (_e, data) => cb(data)),
  ajSave: (j) => ipcRenderer.invoke('aj-save', j),
  ajImport: () => ipcRenderer.invoke('aj-import'),
  ajExport: (month, name) => ipcRenderer.invoke('aj-export', month, name),
  attSettings: () => ipcRenderer.invoke('att-settings'),
  attChooseRoot: () => ipcRenderer.invoke('att-choose-root'),
  attResetRoot: () => ipcRenderer.invoke('att-reset-root'),
  attPickFiles: () => ipcRenderer.invoke('att-pick-files'),
  attClassify: (file) => ipcRenderer.invoke('att-classify', file),
  attSave: (file, meta) => ipcRenderer.invoke('att-save', file, meta),
  attShow: (file) => ipcRenderer.invoke('att-show', file),
  attOpenRoot: () => ipcRenderer.invoke('att-open-root'),
  /** Путь к перетащенному в окно файлу. */
  pathForFile: (file) => webUtils.getPathForFile(file),
});
